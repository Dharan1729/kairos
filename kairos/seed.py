"""Loads the synthetic demo org (kairos/demo_data/*.json) into the
database and creates dev credentials.

Usage: kairos seed   (or python -m kairos.seed)

Writes two keys to $KAIROS_HOME/dev_keys.json (default ./.kairos), readable
only by you:
  admin      an unbound admin service key (can act as any demo user)
  demo_user  a member key bound to DEMO_PERSON_ID (what an agent should use)
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from sqlalchemy.orm import Session as OrmSession

from kairos.auth import generate_api_key
from kairos.config import kairos_home
from kairos.db import configure, create_all, get_sessionmaker
from kairos.directory import Org, Person, Project, SessionRecord, Team
from kairos.knowledge import create_knowledge_item
from kairos.models import TenantConfig

DATA_DIR = Path(__file__).resolve().parent / "demo_data"  # generated by knowledge-layer/generate_synthetic_org.py
DEMO_TENANT_ID = "default"
DEMO_PERSON_ID = "person-team-platform-0"


def dev_keys_file() -> Path:
    return kairos_home() / "dev_keys.json"


def load_dev_key(name: str = "admin") -> str | None:
    path = dev_keys_file()
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text()).get(name)
    except (OSError, ValueError):
        return None


def _load(data_dir: Path, name: str):
    return json.loads((data_dir / name).read_text())


def seed(db: OrmSession, data_dir: Path | None = None, tenant_id: str = DEMO_TENANT_ID) -> str | None:
    """Seeds the demo org. Returns a raw admin key on first seed, or None if
    the database already holds an org."""
    data_dir = data_dir or DATA_DIR
    if db.query(Org).count() > 0:
        return None

    org = _load(data_dir, "org.json")
    db.add(
        Org(
            id=org["id"], name=org["name"], policies=json.dumps(org["policies"]), standards=json.dumps(org["standards"])
        )
    )
    for t in _load(data_dir, "teams.json"):
        db.add(Team(id=t["id"], org_id=t["org_id"], name=t["name"]))
    for p in _load(data_dir, "people.json"):
        db.add(Person(id=p["id"], name=p["name"], role=p["role"], team_id=p["team_id"], manager_id=p.get("manager_id")))
    for pr in _load(data_dir, "projects.json"):
        db.add(Project(id=pr["id"], team_id=pr["team_id"], name=pr["name"], repo_name=pr["repo_name"]))
    for s in _load(data_dir, "sessions.json"):
        db.add(
            SessionRecord(
                id=s["id"],
                person_id=s["person_id"],
                project_id=s["project_id"],
                task_description=s["task_description"],
                timestamp=s.get("timestamp"),
                recent_messages=json.dumps(s.get("recent_messages", [])),
            )
        )
    db.add(TenantConfig(tenant_id=tenant_id, org_id=org["id"], default_budget_tokens=4000))
    db.flush()

    for item in _load(data_dir, "context_items.json"):
        create_knowledge_item(
            db,
            layer=item["layer"],
            scope_id=item["scope_id"],
            content=item["content"],
            staleness_hint=item.get("staleness_hint", "medium"),
            confidence=item.get("confidence", 1.0),
            origin="human",
            item_id=item["id"],
        )

    return generate_api_key(db, tenant_id=tenant_id, label="dev admin (service) key", role="admin")


def write_dev_keys(keys: dict[str, str]) -> Path:
    path = dev_keys_file()
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        json.dump(keys, f, indent=2)
    return path


def seed_with_dev_keys() -> dict[str, str] | None:
    """Creates tables, seeds, writes dev keys. None if already seeded."""
    configure()
    create_all()
    db = get_sessionmaker()()
    try:
        admin_key = seed(db)
        if admin_key is None:
            return None
        user_key = generate_api_key(
            db, tenant_id=DEMO_TENANT_ID, label=f"dev key for {DEMO_PERSON_ID}", role="member", person_id=DEMO_PERSON_ID
        )
        db.commit()
    finally:
        db.close()
    keys = {"admin": admin_key, "demo_user": user_key, "demo_user_id": DEMO_PERSON_ID}
    write_dev_keys(keys)
    return keys


def main():
    keys = seed_with_dev_keys()
    if keys is None:
        print(
            f"Database already seeded. Dev keys from the first seed are in {dev_keys_file()} "
            "(if you deleted that file, delete the database and seed again)."
        )
        return
    print("Seeded the demo org from kairos/demo_data/.")
    print(f"Dev keys written to {dev_keys_file()} (mode 600):")
    print(f"  admin      (service key, can act as any demo user): {keys['admin']}")
    print(f"  demo_user  (bound to {DEMO_PERSON_ID}):            {keys['demo_user']}")


if __name__ == "__main__":
    main()
