"""Adversarial tests for the bundle cache and scope resolution.

Each test tries to get context it should not have, with the cache warmed by
the victim first so a cache leak would show up as well as a resolution leak.

Demo org facts used here (kairos/demo_data, generated by knowledge-layer/):
  person-team-platform-0 (A) owns session-0 on proj-orchestrator-core,
      personal item ctx-personal-person-team-platform-0, session item ctx-session-0
  person-team-platform-mgr (B) is on the same team, owns session-4 and session-8
  person-team-ml-2 is on team-ml, owns session-1 on proj-perception-model
"""

import json

import pytest
from sqlalchemy import text

from kairos.directory import Person
from kairos.models import CacheEntry, KnowledgeItem

A, B, ML = "person-team-platform-0", "person-team-platform-mgr", "person-team-ml-2"
TASK = "Add a /healthz endpoint to a new internal service"
A_PRIVATE = {"ctx-personal-person-team-platform-0", "ctx-session-0"}
PLATFORM_ONLY = {"ctx-3", "ctx-4", "ctx-7"}  # team-platform and proj-orchestrator-core items


def post(c, user=None, session=None, repo=None, task=TASK, budget=4000, path="/v1/assemble_context"):
    body = {
        "context_principal": {"user_id": user, "session_id": session, "repo": repo, "agent_type": "test"},
        "budget_tokens": budget,
    }
    body.update({"task": {"description": task}} if path.endswith("assemble_context") else {"query": task})
    return c.post(path, json=body)


def sources(resp) -> set[str]:
    assert resp.status_code == 200, resp.text
    body = resp.json()
    return {i["source"] for i in body.get("context_bundle", body.get("results", []))}


@pytest.fixture(params=[False, True], ids=["per-user-cache", "cross-user-cache"])
def cross_user(request, monkeypatch):
    monkeypatch.setenv("KAIROS_CACHE_CROSS_USER_REUSE", "true" if request.param else "false")
    return request.param


# ---- personal and session layers --------------------------------------------


def test_victim_bundle_contains_their_private_items(client, make_key, as_key):
    """Sanity check for the tests below: A does see A's private items."""
    a = as_key(make_key(person_id=A))
    assert A_PRIVATE <= sources(post(a, session="session-0"))


def test_naming_another_users_session_is_refused(client, make_key, as_key, cross_user):
    a, b = as_key(make_key(person_id=A)), as_key(make_key(person_id=B))
    sources(post(a, session="session-0"))  # warm the cache with A's bundle
    assert post(b, session="session-0").status_code == 403
    assert post(b, user=B, session="session-0").status_code == 403


def test_bound_key_cannot_claim_another_user(client, make_key, as_key, cross_user):
    a, b = as_key(make_key(person_id=A)), as_key(make_key(person_id=B))
    sources(post(a, session="session-0"))
    assert post(b, user=A).status_code == 403
    assert post(b, user=A, path="/v1/search_knowledge").status_code == 403


def test_same_task_same_project_never_serves_another_users_private_items(client, make_key, as_key, cross_user):
    a, b = as_key(make_key(person_id=A)), as_key(make_key(person_id=B))
    sources(post(a, session="session-0"))
    got = sources(post(b, session="session-8"))  # B's own session on the same project, same task text
    assert not got & A_PRIVATE
    got_repo = sources(post(b, repo="nimbus/orchestrator-core"))
    assert not got_repo & A_PRIVATE


def test_admin_service_key_acting_for_b_gets_only_bs_private_items(client, make_key, as_key):
    a = as_key(make_key(person_id=A))
    sources(post(a, session="session-0"))
    got = sources(post(client, user=B, session="session-8"))
    assert not got & A_PRIVATE
    assert "ctx-personal-person-team-platform-mgr" in got


def test_unbound_member_key_gets_org_layer_only(client, make_key, as_key):
    svc = as_key(make_key(role="member"))
    assert post(svc, user=A, session="session-0").status_code == 403  # cannot prove the session is its own
    resp = post(svc, user=A, repo="nimbus/orchestrator-core")
    assert resp.status_code == 200
    assert [r["layer"] for r in resp.json()["scope"]["layers"]] == ["org"]
    assert {i["layer"] for i in resp.json()["context_bundle"]} <= {"org"}


def test_cross_user_reuse_shares_only_between_users_without_private_items(
    client, make_key, as_key, db_session, monkeypatch
):
    monkeypatch.setenv("KAIROS_CACHE_CROSS_USER_REUSE", "true")
    for pid in ("p-new-1", "p-new-2"):
        db_session.add(Person(id=pid, name=pid, team_id="team-platform"))
    db_session.commit()
    n1, n2 = as_key(make_key(person_id="p-new-1")), as_key(make_key(person_id="p-new-2"))
    a = as_key(make_key(person_id=A))
    repo = "nimbus/orchestrator-core"
    assert post(n1, repo=repo).json()["cache"]["outcome"] == "miss"
    shared = post(n2, repo=repo).json()
    assert shared["cache"]["outcome"] == "hit"  # identical readable knowledge: safe to share
    a_resp = post(a, repo=repo).json()
    assert a_resp["cache"]["outcome"] == "miss"  # A has private items: never shares
    monkeypatch.setenv("KAIROS_CACHE_CROSS_USER_REUSE", "false")
    assert post(n2, repo=repo, task=TASK + " now").json()["cache"]["outcome"] == "miss"


# ---- team boundary ----------------------------------------------------------


def test_other_teams_repo_is_not_readable(client, make_key, as_key, cross_user):
    platform, ml = as_key(make_key(person_id=A)), as_key(make_key(person_id=ML))
    sources(post(platform, repo="nimbus/orchestrator-core"))  # warm with team-platform's bundle
    resp = post(ml, repo="nimbus/orchestrator-core")
    got = sources(resp)
    assert not got & PLATFORM_ONLY
    assert "team-platform" not in {r["scope_id"] for r in resp.json()["scope"]["layers"]}
    assert any("another team" in n for n in resp.json()["scope"]["notes"])
    assert not sources(post(ml, repo="nimbus/orchestrator-core", path="/v1/search_knowledge")) & PLATFORM_ONLY


def test_admin_service_key_cannot_widen_a_users_team(client):
    got = sources(post(client, user=ML, repo="nimbus/orchestrator-core"))
    assert not got & PLATFORM_ONLY


# ---- invalidation -----------------------------------------------------------


def _warm(c, session="session-0"):
    first = post(c, session=session)
    assert first.json()["cache"]["outcome"] in ("miss", "hit")
    assert post(c, session=session).json()["cache"]["outcome"] == "hit"
    return first.json()


def test_revised_item_is_never_served_stale(client, make_key, as_key):
    a = as_key(make_key(person_id=A))
    _warm(a)
    resp = client.post(
        "/v1/knowledge_items/ctx-0/revise",
        json={"content": "All services must expose /livez and /readyz (replaces /healthz)."},
    )
    assert resp.status_code == 200
    after = post(a, session="session-0").json()
    assert after["cache"]["outcome"] == "miss"
    contents = " ".join(i["content"] for i in after["context_bundle"])
    assert "ctx-0" not in {i["source"] for i in after["context_bundle"]}
    assert "/livez" in contents


def test_orm_in_place_edit_is_never_served_stale(client, make_key, as_key, db_session):
    a = as_key(make_key(person_id=A))
    _warm(a)
    item = db_session.get(KnowledgeItem, "ctx-session-0")
    item.content = "Working notes: EDITED IN PLACE."
    db_session.commit()
    after = post(a, session="session-0").json()
    assert after["cache"]["outcome"] != "hit"
    assert any(i["content"] == "Working notes: EDITED IN PLACE." for i in after["context_bundle"])


def test_raw_sql_edit_is_caught_by_content_check_on_hit(client, make_key, as_key, db_session):
    a = as_key(make_key(person_id=A))
    _warm(a)
    db_session.execute(text("UPDATE knowledge_items SET content = 'RAW SQL EDIT' WHERE id = 'ctx-session-0'"))
    db_session.commit()
    after = post(a, session="session-0").json()
    assert after["cache"]["outcome"] == "stale"
    assert any(i["content"] == "RAW SQL EDIT" for i in after["context_bundle"])


def test_expired_item_is_never_served_from_cache(client, make_key, as_key, db_session):
    a = as_key(make_key(person_id=A))
    _warm(a)
    db_session.execute(
        text("UPDATE knowledge_items SET valid_until = '2000-01-01 00:00:00' WHERE id = 'ctx-session-0'")
    )
    db_session.commit()
    after = post(a, session="session-0").json()
    assert after["cache"]["outcome"] != "hit"
    assert "ctx-session-0" not in {i["source"] for i in after["context_bundle"]}


def test_new_item_in_a_readable_scope_invalidates(client, make_key, as_key):
    a = as_key(make_key(person_id=A))
    _warm(a)
    assert (
        a.post(
            "/v1/knowledge_items",
            json={"layer": "personal", "scope_id": A, "content": "Prefers /healthz handlers in handlers/health.py"},
        ).status_code
        == 200
    )
    assert post(a, session="session-0").json()["cache"]["outcome"] == "miss"


def test_tampered_cache_entry_with_unreadable_item_is_not_served(client, make_key, as_key, db_session):
    """Defence in depth: even if a bundle holding another user's item somehow
    landed in B's partition, the hit-time check refuses to serve it."""
    a, b = as_key(make_key(person_id=A)), as_key(make_key(person_id=B))
    sources(post(a, session="session-0"))
    sources(post(b, session="session-8"))
    b_entry = db_session.query(CacheEntry).order_by(CacheEntry.created_at.desc()).first()
    poisoned = json.loads(b_entry.bundle)
    victim = db_session.get(KnowledgeItem, "ctx-personal-person-team-platform-0")
    poisoned["bundle"].append({"layer": "personal", "content": victim.content, "source": victim.id})
    from kairos.models import content_hash

    contributing = json.loads(b_entry.contributing) + [[victim.id, content_hash(victim.content)]]
    b_entry.bundle, b_entry.contributing = json.dumps(poisoned), json.dumps(contributing)
    db_session.commit()
    resp = post(b, session="session-8")
    assert resp.json()["cache"]["outcome"] == "stale"
    assert victim.id not in sources(resp)
